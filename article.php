          modal.find('.appointment-second p').text('');
          modal.find('.appointment-second ul.description').remove();
          modal.find('.appointment-second ul').empty();
          modal.find('.appointment-first img.doc-img-modal').attr('src', 'https://www.image-dent.com/assets/images/doctors/default_doctor.jpg');
          modal.find('.book-service-modal-btn').attr('data-doctor-id', '');
          
    $.ajax({
      url: 'fetch_doctor.php',
      method: 'GET',
      data: {
        id: doctorId
      },
      dataType: 'json',
      success: function(data) {
        console.log(data);

        if (data.error) {
          modal.find('.appointment-second h2').text('Doctor not found');
          return;
        }

        modal.find('.appointment-second h2').text(data.title);
        modal.find('.appointment-second p').text(data.details);

        modal.find('.appointment-second ul.description').remove();

        if (typeof data.description === 'string') {
          var tempDiv = $('<div>').html(data.description);
          var ul = $('<ul class="description"></ul>');
          tempDiv.find('p').each(function() {
            var txt = $(this).html().replace(/&nbsp;|\u00A0/g, '').trim();
            if (txt.length > 0) {
              ul.append('<li><img src="assets/images/bullet.svg" alt="">' + $(this).html() + '</li>');
            }
          });
          modal.find('.appointment-second p').after(ul);
        }

        modal.find('.appointment-second ul:not(.description)').empty();
        modal.find('.appointment-first img.doc-img-modal').attr('src', 'https://www.image-dent.com/assets/images/doctors/' + data.images);

        // Pass doctor id to booking button
        modal.find('.book-service-modal-btn').attr('data-doctor-id', data.id);
      },
      error: function() {
        modal.find('.appointment-second h2').text('Error loading doctor info');
        modal.find('.appointment-second p').text('');
        modal.find('.appointment-second ul.description').remove();
        modal.find('.appointment-second ul').empty();
        modal.find('.appointment-first img.doc-img-modal').attr('src', '');
        modal.find('.book-service-modal-btn').attr('data-doctor-id', '');
      }
    });
  });


