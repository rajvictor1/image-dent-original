document.addEventListener('DOMContentLoaded', () => {
  forms.forEach(({ formId, errorId, widgetIdVar }) => {
    const form = document.getElementById(formId);
    const errorElement = document.getElementById(errorId);

    if (!form || !errorElement) return;

    form.addEventListener('submit', e => {
      let valid = true;
      errorElement.style.display = 'none';
      errorElement.textContent = '';

      form.querySelectorAll('small.text-danger').forEach(el => {
        el.style.display = 'none';
        el.textContent = '';
      });

      const bookingDateInput = form.querySelector('input[name="booking_date"]');
      const selectedDate = bookingDateInput ? new Date(bookingDateInput.value) : null;
      const today = new Date();
      today.setHours(0, 0, 0, 0);

      const bookingDateError = form.querySelector('.error-booking_date');

      ['first_name', 'last_name', 'email', 'phone', 'message', 'booking_date', 'time_slot'].forEach(field => {
        const input = form.querySelector(`[name=${field}]`);
        if (input) {
          let val = input.value.trim();
          if (val === '') {
            showError(form, field, `${messages.please_enter} ${(fieldLabels[field] || field)}`);
            valid = false;
          }
          if (field === 'email' && val !== '') {
            const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
            if (!emailRegex.test(val)) {
              showError(form, 'email', messages.valid_email);
              valid = false;
            }
          }
          if (field === 'phone' && val !== '') {
            const phoneRegex = /^\d{8,15}$/;
            if (!phoneRegex.test(val)) {
              showError(form, 'phone', messages.valid_phone);
              valid = false;
            }
          }
          if (field === 'booking_date' && val !== '') {
            if (selectedDate < today) {
              valid = false;
              if (bookingDateError) {
                bookingDateError.textContent = messages.date_current_or_future;
                bookingDateError.style.display = "block";
              }
            }
          }
        }
      });

      if (!grecaptcha.getResponse(widgetIdVar())) {
        valid = false;
        errorElement.textContent = messages.captcha_required;
        errorElement.style.display = 'block';
      }

      if (!valid) e.preventDefault();
    });
  });
});

function showError(form, fieldName, message) {
  const el = form.querySelector(`small.error-${fieldName}`);
  if (el) {
    el.textContent = message;
    el.style.display = 'block';
  }
}

