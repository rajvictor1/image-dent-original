$(document).ready(function() {
  // Localized option labels from PHP
  var selectDoctorText = "اختر الطبيب";
  var loadingText = "...جاري التحميل";
  var noDoctorsText = "لم يتم العثور على أطباء";

  $('#treatment-dropdown').on('change', function() {
    var selectedTreatment = $(this).val();
    var doctorDropdown = $('#doctor-dropdown');
    doctorDropdown.html('<option value="">' + loadingText + '</option>');
    if (selectedTreatment) {
      $.ajax({
        url: 'https://www.image-dent.com//get_doctors_by_service.php',
        type: 'GET',
        data: {
          service: selectedTreatment
        },
        dataType: 'json',
        success: function(response) {
          var options = '<option value="">' + selectDoctorText + '</option>';
          $.each(response, function(index, doctor) {
            options += '<option value="' + doctor.name + '">' + doctor.name + '</option>';
          });
          doctorDropdown.html(options);
        },
        error: function() {
          doctorDropdown.html('<option value="">' + noDoctorsText + '</option>');
        }
      });
    } else {
      doctorDropdown.html('<option value="">' + selectDoctorText + '</option>');
    }
  });
});
</script>

